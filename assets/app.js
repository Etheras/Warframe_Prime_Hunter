  /* ── collection toggles ───────────────────────────────────── */
  function toggle(id) {
    const it = ITEMS.find((x) => x.id === id);
    const want = !collected.has(id);
    if (it && it.parts.length) {
      // parts are the source of truth for anything that has them
      setAllParts(it, want);
      syncCollected(it);
    } else if (want) {
      collected.add(id);
    } else {
      collected.delete(id);
    }
    saveCollected();
    // the card also carries a parts counter now, so redraw it wholesale
    if (it && !matches(it)) {
      render();   // filtered out — must disappear immediately
    } else {
      const card = grid.querySelector(`.card[data-id="${CSS.escape(id)}"]`);
      if (card) card.outerHTML = cardHTML(it);
      updateProgress(); updateCounts(); refreshHeadings();
    }
  }

  function refreshHeadings() {
    if (state.sort !== "cat") return;
    $$(".cat-heading").forEach((h) => {
      const cat = h.childNodes[0].textContent.trim();
      const inCat = shown.filter((x) => x.category === cat);
      const got = inCat.filter((x) => collected.has(x.id)).length;
      const p = h.querySelector(".cat-prog");
      if (p) p.textContent = `${got}/${inCat.length}`;
    });
    const got = shown.filter((x) => collected.has(x.id)).length;
    $("#resultCount").innerHTML =
      `<b>${shown.length}</b> of ${ITEMS.length} shown · <b>${got}</b> collected here`;
  }

