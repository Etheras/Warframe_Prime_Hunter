  /* ── farm spot aggregation ────────────────────────────────────
     The question this app exists to answer: which single mission
     gives me the most relics for this frame?                      */
  /* Only relics that still hold something you're missing. Falls back to the
     full set once the item is complete, so the view never goes blank. */
  function relicsStillNeeded(it) {
    const need = new Set();
    (it.parts || []).forEach((p) => {
      if (haveOf(it.id, p.name) >= needOf(p)) return;
      p.relics.forEach((r) => need.add(r.relic));
    });
    return need.size ? need : new Set(it.relics || []);
  }

  /* What one opening of this relic is worth for the parts of `it` you still
     need, at whichever refinement suits them best. Same model the planner uses,
     so the two pages cannot disagree about what "best" means. */
  function relicValueFor(it, rname) {
    const slots = [];
    (it.parts || []).forEach((p) => {
      if (haveOf(it.id, p.name) >= needOf(p)) return;
      const hit = p.relics.find((r) => r.relic === rname);
      if (hit && hit.chances) slots.push(hit.chances);
    });
    if (!slots.length) return 0;
    const order = (DATA.meta && DATA.meta.refinements) ||
      ["Intact", "Exceptional", "Flawless", "Radiant"];
    let best = 0;
    order.forEach((f) => {
      let v = 0;
      slots.forEach((ch) => { if (ch[f] != null) v += squadify(ch[f]) / 100; });
      if (v > best) best = v;
    });
    return best;
  }

  function bestSpots(it) {
    const needed = relicsStillNeeded(it);
    const open = (it.relics || []).filter(
      (r) => RELICS[r] && !RELICS[r].vaulted && needed.has(r));

    const value = new Map();
    open.forEach((r) => value.set(r, relicValueFor(it, r)));

    /* Railjack nodes are kept here, unlike in the planner. This view answers
       "where does this item's relic drop", not "where should I go next", and
       some live relics drop nowhere else: Nyx Prime's only unvaulted relic is
       Neo V9, which exists on four Proxima nodes and nowhere on the star chart.
       Filtering them out left that card with no farm section at all - the page
       said nothing where it could have said "here, and you will need a ship".
       Now it says exactly that, on the row, via the Railjack badge. */
    const map = new Map();
    open.forEach((rname) => {
      if (!value.get(rname)) return;
      (RELICS[rname].sources || [])
        .filter((s) => !ROT.notADestination(s) && !isEventNode(s))
        .forEach((s) => {
        const key = `${s.planet} ${s.node} ${s.mode}`;
        let e = map.get(key);
        if (!e) {
          e = { planet: s.planet, node: s.node, mode: s.mode, kind: s.kind,
                relics: new Map(), event: s.event, score: 0, lvl: s.lvl || null,
                rot: { A: 0, B: 0, C: 0, none: 0 }, perRot: new Map() };
          map.set(key, e);
        }
        // A relic can be listed on more than one rotation at the same node, and
        // a run that reaches rotation C has collected the A and B rewards too -
        // so every rotation gets its own bucket, best chance per relic in each.
        const slot = rotSlot(s.rotation);
        const worth = ((s.chance || 0) / 100) * value.get(rname);
        const rk = rname + "|" + slot;
        const prev = e.perRot.get(rk);
        if (prev == null || worth > prev) {
          e.rot[slot] += worth - (prev || 0);
          e.perRot.set(rk, worth);
        }
        const shown = e.relics.get(rname);
        if (!shown || (s.chance || 0) > (shown.chance || 0)) {
          e.relics.set(rname, { chance: s.chance, rotation: s.rotation });
        }
        if (!e.lvl && s.lvl) e.lvl = s.lvl;
      });
    });

    /* Value each node as a whole run, the same way the planner does — and now
       that includes deciding how far to run it, which is why the fissure test
       has to happen here too. Both pages call the same function with the same
       answer, so neither can cost a run at a length the other disagrees with.

       Void Storms are allowed, as everywhere on this page: it never hides
       Railjack, since some live relics drop nowhere else.

       **The Steel Path is refused, and the two arguments are not symmetrical.**
       A storm is a place a relic really drops; a Steel Path fissure is the same
       relic on a chart the reader may not be standing on, and running the
       ordinary node cracks nothing. This page has no planner options to read, so
       it takes the default rather than a preference - passed explicitly, because
       an omitted argument that happens to be falsy is not a decision anybody can
       find later. The planner's switch is the only place this is asked. */
    const now = Date.now();
    const isFissureNow = (e) =>
      ROT.fissuresAt(FISSURES, nodeKey(e), now, true, false).length > 0;
    map.forEach((e) => {
      const live = e.kind === "bounty" ? liveRotation(e.node) : null;
      const r = runValue(e.rot, e.mode, state.squad, live, null,
                         !ROT.isRailjack(e) && isFissureNow(e));
      e.score = r.total; e.perRound = r.perRound;
      e.rounds = r.rounds; e.counts = r.counts;
      e.stranded = r.stranded; e.nonStandard = r.nonStandard;
      e.planName = r.planName; e.bounty = r.bounty; e.runMode = r.mode;
      /* Both pages have to name a run's cost the same way, and `rounds` is not
         that name - it counts *rewards*, and Onslaught pays one per two zones.
         So ask the shared function rather than printing `rounds` here, which is
         what the planner does. This page still ranks per run and has no effort
         panel; it only needs the words. */
      const o = ROT.objectivesOf(e);
      e.objectives = o.count; e.unit = o.unit;
    });

    const ranked = Array.from(map.values())
      .map((e) => ({
        ...e,
        count: e.relics.size,
        best: Math.max.apply(null,
          Array.from(e.relics.values()).map((v) => v.chance || 0).concat([0])),
        // the run is costed to a fixed depth, so only name the rotations it
        // actually reaches - listing C when you stop after round 2 is a lie
        rotations: e.counts
          ? Object.keys(e.counts).filter((r) => (e.rot[r] || 0) > 0)
          : [],
        nonStandard: e.nonStandard,
        // best-first, matching the planner: chance here x what an opening is worth
        relicList: Array.from(e.relics.entries())
          .map(([name, v]) => [name, ((v.chance || 0) / 100) * (value.get(name) || 0)])
          .sort((a, b) => b[1] - a[1])
          .map(([name]) => name),
      }))
      // Rank by what a round here is worth towards what is still wanted - not
      // by how many relics happen to overlap, which is what used to make this
      // list disagree with the per-part relic odds below it. Rotation is in the
      // score now, so it is not a tie-break as well.
      .sort((a, b) => {
        if (Math.abs(b.score - a.score) > 1e-9) return b.score - a.score;
        const al = a.lvl ? a.lvl[0] : Infinity, bl = b.lvl ? b.lvl[0] : Infinity;
        if (al !== bl) return al - bl;
        return (a.node || "").localeCompare(b.node || "");
      });

    /* Fold nodes that are the same bet, exactly as the planner does and through
       the same two functions, so the two pages cannot disagree about what
       counts as a duplicate or which of a group to name. Eight rows for one
       choice wastes a list that only shows eight.

       `pickNode` takes the fissure test as an argument and this page used to
       leave it out, which broke the second half of that promise: with a fissure
       live at a member that is not the lowest-level one, the planner named that
       node and this page named another. Same predicate, same answer. Void
       Storms count here where they may not on the planner - this view never
       hides Railjack, since some live relics drop nowhere else. */
    const order = [];
    const groups = new Map();
    ranked.forEach((e) => {
      const key = ROT.signature(e);
      if (groups.has(key)) { groups.get(key).push(e); return; }
      groups.set(key, [e]);
      order.push(key);
    });
    // the same test the scoring above used, so the fold cannot name a node the
    // scoring costed differently
    return order.map((key) => {
      const group = groups.get(key);
      const pick = group.length > 1 ? ROT.pickNode(group, isFissureNow) : group[0];
      pick.sameAs = group.length > 1 ? group : null;
      pick.pickedForFissure = !!(pick.sameAs && isFissureNow(pick));
      return pick;
    });
  }
